package app.tryst.ui.common

import android.content.Context
import android.net.Uri
import android.provider.OpenableColumns
import java.io.InputStream

/**
 * Opens a picked photo and reads its display name. Photos arrive through the system document picker, which
 * (unlike the Android Photo Picker) hands over the original file with its GPS and camera tags intact, so
 * no media-location permission is needed.
 */
object PhotoSource {

    fun open(context: Context, uri: Uri): InputStream? = runCatching { context.contentResolver.openInputStream(uri) }.getOrNull()

    /** The file name the provider reports for [uri], for the photo's details; null when unavailable. */
    fun displayName(context: Context, uri: Uri): String? = runCatching {
        context.contentResolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use { c ->
            if (c.moveToFirst()) c.getString(0)?.takeIf { it.isNotBlank() } else null
        }
    }.getOrNull()
}

